from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).parent))

from utils import (
    data_dir, get_logger, get_spec_by_id, load_json,
    load_text, outputs_dir, repo_root,
)
from validator import validate_spec
from parser import extract_tla_from_response
from runner import _call_model

logger = get_logger("preference_generator")


def _get_description(spec_id: int) -> str | None:
    """Return the system_overview description for spec_id, or None if not available."""
    desc_file = data_dir() / "TLA_Description.json"
    if not desc_file.exists():
        return None
    descriptions = load_json(desc_file)
    if not isinstance(descriptions, list) or spec_id >= len(descriptions):
        return None
    entry = descriptions[spec_id]
    if not isinstance(entry, dict):
        return None
    desc = entry.get("description", {})
    if isinstance(desc, dict):
        return desc.get("system_overview") or None
    if isinstance(desc, str):
        return desc or None
    return None


def _get_ground_truth_tla(spec_id: int) -> str | None:
    """Return the ground-truth TLA+ source for spec_id from data/tla_files/."""
    tla_path = data_dir() / "tla_files" / f"{spec_id}.tla"
    if not tla_path.exists():
        return None
    return tla_path.read_text(encoding="utf-8")


def _build_prompt(spec_id: int) -> str | None:
    """Build the nlp_to_tla prompt using the real English description."""
    prompt_file = repo_root() / "configs" / "prompts" / "nlp_to_tla.txt"
    if not prompt_file.exists():
        logger.warning("Missing prompt file: %s", prompt_file)
        return None
    description = _get_description(spec_id)
    if not description:
        logger.warning("spec=%d: no description available, skipping", spec_id)
        return None
    return load_text(prompt_file).replace("{description}", description)


def _validate_tla(tla_source: str, spec_id: int, label: str) -> bool:
    """Run SANY on a TLA+ string. Returns True if it passes."""
    val_dir = outputs_dir() / "preference_validation"
    val_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".tla", delete=False, dir=str(val_dir)
    ) as f:
        f.write(tla_source)
        temp_path = f.name
    try:
        cfg_path = data_dir() / "cfg" / f"{spec_id}.cfg"
        summary = validate_spec(
            temp_path,
            str(cfg_path) if cfg_path.exists() else None,
            str(val_dir),
            spec_id,
            label,
            "nlp_to_tla",
        )
        return summary.get("sany_pass", False)
    except Exception as exc:
        logger.error("spec=%d validation error (%s): %s", spec_id, label, exc)
        return False
    finally:
        try:
            os.unlink(temp_path)
        except OSError:
            pass


def generate_preference_dataset(
    spec_ids: list[int],
    model_config: dict[str, Any],
    num_candidates: int = 5,
    output_path: Path | None = None,
) -> list[dict[str, Any]]:
    """Build a PVP preference dataset.

    For each spec:
      chosen   = ground-truth TLA+ from data/tla_files/ (always valid)
      rejected = a candidate generated by the model that fails SANY
    """
    if output_path is None:
        output_path = outputs_dir() / "preference_dataset.jsonl"

    all_pairs = []

    for spec_id in spec_ids:
        # --- chosen: ground-truth spec ---
        chosen = _get_ground_truth_tla(spec_id)
        if not chosen:
            logger.warning("spec=%d: no ground-truth TLA+ file, skipping", spec_id)
            continue

        # --- prompt: real English description ---
        prompt = _build_prompt(spec_id)
        if not prompt:
            continue

        # --- rejected: model-generated spec that fails SANY ---
        rejected = None
        for attempt in range(num_candidates):
            try:
                result = _call_model(model_config, prompt)
                extracted = extract_tla_from_response(result["text"])
                if not extracted:
                    continue
                if not _validate_tla(extracted, spec_id, f"{model_config['id']}_attempt{attempt}"):
                    rejected = extracted
                    break  # found a failing candidate — use it
            except Exception as exc:
                logger.error("spec=%d attempt=%d: %s", spec_id, attempt, exc)

        if rejected is None:
            logger.warning(
                "spec=%d: could not obtain a rejected candidate in %d attempts",
                spec_id, num_candidates,
            )
            continue

        all_pairs.append({
            "spec_id":   spec_id,
            "condition": "nlp_to_tla",
            "prompt":    prompt,
            "chosen":    chosen,
            "rejected":  rejected,
        })
        logger.info("spec=%d: pair added (total so far: %d)", spec_id, len(all_pairs))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        for pair in all_pairs:
            f.write(json.dumps(pair) + "\n")

    logger.info("Preference dataset saved: %s (%d pairs)", output_path, len(all_pairs))
    return all_pairs


def main():
    import argparse

    parser = argparse.ArgumentParser(description="Generate PVP preference dataset from train split")
    parser.add_argument("--limit",      type=int,  default=None,               help="Limit number of train specs")
    parser.add_argument("--candidates", type=int,  default=5,                  help="Max attempts to find a rejected candidate")
    parser.add_argument("--model",      type=str,  default="qwen2.5-coder:32b", help="Ollama model for rejected candidate generation")
    parser.add_argument("--output",     type=Path, default=None,               help="Output JSONL path")
    args = parser.parse_args()

    # Train IDs only — test IDs are held out for evaluation
    split    = load_json(data_dir() / "test_split.json")
    spec_ids = split["train_ids"]
    if args.limit:
        spec_ids = spec_ids[:args.limit]

    model_cfg = {
        "id":           args.model,
        "backend":      "ollama",
        "model_name":   args.model,
        "temperature":  0.7,
        "max_tokens":   4096,
    }

    logger.info(
        "Generating preference dataset: %d train specs, model=%s, max_candidates=%d",
        len(spec_ids), args.model, args.candidates,
    )

    generate_preference_dataset(
        spec_ids=spec_ids,
        model_config=model_cfg,
        num_candidates=args.candidates,
        output_path=args.output,
    )


if __name__ == "__main__":
    main()
